"""
Строит data/enrichment.csv из data/products.csv, применяя вручную
подобранные правила сопоставления по ключевому слову в Наименовании.

Это НЕ генератор контента — весь текст сценариев придуман человеком на
основе знания о товарах, ничего не создаётся автоматически. Смысл держать
это кодом, а не просто статичным enrichment.csv: правило "если в названии
есть Х — добавить сценарий Y" переживает обновление каталога. products.csv
выгружается из 1С заново каждый день — если завтра появится новый артикул
с тем же словом ("Насос для шаров XL"), повторный запуск этого файла
подхватит его автоматически; статичная построчная таблица, привязанная к
сегодняшним артикулам, — нет.

Принцип отбора правил: обогащаем только то, что НЕ выводится из
названия+категории. Категория и название уже говорят "что это"; правило
добавляет "какую проблему это решает" — только для товаров, чья функция
не самоочевидна (насос, клей-точки, сетка для сброса и т.п.). Товар без
совпавшего ключевого слова получает пустой сценарий — это ожидаемо, не
все товары нуждаются в обогащении.

Процесс сопровождения — полу-ручной, не автоматизированный моделью (см.
ARCHITECTURE.md п.9): при появлении новых товаров в 1С человек периодически
просматривает новые артикулы и решает, нужно ли новое правило. Правила
подбираются по слову в названии, НЕ подгоняются под ответы queries.csv —
иначе результат был бы переобучением на тестовую выборку.

Запуск: python build_enrichment.py
(или: docker compose run --rm app python build_enrichment.py)
"""
import csv

# (подстрока в названии, нижний регистр) -> сценарий использования.
# Список подобран человеком, расширяется по находкам при просмотре каталога.
KEYWORD_OVERRIDES: list[tuple[str, str]] = [
    ("насос", "чтобы надуть шарики без гелия"),
    ("клей-точки", "чтобы приклеить шарики к стене или потолку без скотча"),
    ("сетка для сброса", "чтобы красиво запустить или сбросить шары в конце праздника"),
    ("грузик для шаров", "чтобы удержать воздушный шар на месте, не дать ему улететь"),
    ("лента для шаров", "чтобы привязать и оформить связку воздушных шаров"),
    ("топпер", "украшение торта или капкейков"),
    ("дудки", "шумовой аксессуар для праздника"),
    ("свистки", "шумовой аксессуар для праздника"),
    ("хлопушка", "эффектный хлопок с конфетти на празднике"),
    ("растяжка", "настенное украшение-надпись к празднику"),
    ("фотобутафория", "аксессуар для фотосессии на празднике"),
    ("майка", "пакет-майка для покупок"),
    ("петлевой", "пакет с петлевой ручкой для покупок"),
]


def match_scenario(name: str) -> str:
    name_lower = name.lower()
    extras = [extra for keyword, extra in KEYWORD_OVERRIDES if keyword in name_lower]
    return "; ".join(extras)


def main() -> None:
    with open("data/products.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f, delimiter=";"))

    with open("data/enrichment.csv", "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, delimiter=";")
        writer.writerow(["Артикул", "Сценарий"])
        for row in rows:
            writer.writerow([row["Артикул"], match_scenario(row["Наименование"])])

    matched = sum(1 for row in rows if match_scenario(row["Наименование"]))
    print(f"data/enrichment.csv: {len(rows)} строк, из них с текстом: {matched}")


if __name__ == "__main__":
    main()
